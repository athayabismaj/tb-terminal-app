class OwnerDashboardScreenshotTest {

    @get:Rule
    val composeRule = createComposeRule()

    @Test
    @Config(qualifiers = "w390dp-h1320dp-mdpi")
    fun captureOwnerDashboardPhone() {
        composeRule.setContent {
            OwnerDashboardPhoneReferencePreview()
        }
        val output = File("build/roborazzi/owner_dashboard_phone.png").apply { parentFile?.mkdirs() }
        composeRule.onRoot().captureRoboImage(
            file = output,
            roborazziOptions = RoborazziOptions(taskType = RoborazziTaskType.Record)
        )
